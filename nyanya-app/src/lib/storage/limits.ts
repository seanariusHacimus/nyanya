/**
 * Ограничения на загружаемые файлы — в отдельном модуле, чтобы их знал и
 * браузер.
 *
 * Проверять размер на клиенте обязательно, а не «для удобства»: тело
 * серверного действия режет сама платформа (`serverActions.bodySizeLimit` в
 * next.config.ts), и делает это ДО того, как действие запустится. Значит наша
 * серверная проверка слишком большой файл увидеть не может в принципе — вместо
 * человеческого объяснения пользователь получал аварийную страницу. Отсечь
 * такой файл способен только тот, кто ещё не отправил запрос, то есть браузер.
 *
 * Серверная проверка при этом остаётся: клиенту доверять нельзя, запрос можно
 * послать и мимо формы.
 */

export const MAX_FILE_BYTES = 10 * 1024 * 1024; // 10 МБ

export const ALLOWED_MIME = [
  "image/jpeg",
  "image/png",
  "image/webp",
  "image/heic",
  "application/pdf",
] as const;

export function isAllowedMime(mime: string): boolean {
  return (ALLOWED_MIME as readonly string[]).includes(mime);
}

/** «10 МБ» — для сообщений пользователю, чтобы число не разъезжалось с кодом. */
export const MAX_FILE_LABEL = `${Math.round(MAX_FILE_BYTES / 1024 / 1024)} МБ`;
